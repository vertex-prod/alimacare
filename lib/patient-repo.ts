export async function createPatient(
  input: CreatePatientInput
): Promise<Patient> {
  // `patient_id`, `department`, and the daily ticket number are generated by
  // the database. Optional blank fields are omitted so PostgreSQL defaults
  // and NULLs apply.
  const row: Record<string, unknown> = {
    respondent_role: input.respondentRole,
    visit_purpose: input.visitPurpose,
    full_name: input.fullName,
    identity_unknown: input.identityUnknown ?? false,
    age: input.age,
    sex: input.sex,
    chief_complaint: input.chiefComplaint,
    priority_lane: input.priorityLane,
    payment_type: input.paymentType,
    consent_given: input.consentGiven,
    status: input.status ?? "PENDING_RECEPTION",
  };

  if (input.patientId) row.patient_id = input.patientId;
  if (input.dob) row.dob = input.dob;
  if (input.civilStatus) row.civil_status = input.civilStatus;
  if (input.address) row.address = input.address;
  if (input.contactNumber) row.contact_number = input.contactNumber;
  if (input.allergies) row.allergies = input.allergies;
  if (input.hasRequestSlip !== undefined) {
    row.has_request_slip = input.hasRequestSlip;
  }
  if (input.hmoProvider) row.hmo_provider = input.hmoProvider;
  if (input.hmoNo) row.hmo_no = input.hmoNo;
  if (input.philhealthPin) row.philhealth_pin = input.philhealthPin;
  if (input.employerName) row.employer_name = input.employerName;
  if (input.roomPreference) row.room_preference = input.roomPreference;
  if (input.emergencyContactName) {
    row.emergency_contact_name = input.emergencyContactName;
  }
  if (input.emergencyContactRelationship) {
    row.emergency_contact_relationship = input.emergencyContactRelationship;
  }
  if (input.emergencyContactNumber) {
    row.emergency_contact_number = input.emergencyContactNumber;
  }
  if (input.guardianFullName) row.guardian_full_name = input.guardianFullName;
  if (input.guardianRelationship) {
    row.guardian_relationship = input.guardianRelationship;
  }
  if (input.guardianContactNumber) {
    row.guardian_contact_number = input.guardianContactNumber;
  }
  if (input.guardianIdType) row.guardian_id_type = input.guardianIdType;
  if (input.signatureData) row.signature_data = input.signatureData;
  if (input.queueNumber !== undefined) row.queue_number = input.queueNumber;
  if (input.assignedDoctor) row.assigned_doctor = input.assignedDoctor;
  if (input.assignedRoom) row.assigned_room = input.assignedRoom;
  if (input.estimatedWaitMinutes !== undefined) {
    row.estimated_wait_minutes = input.estimatedWaitMinutes;
  }

  const { data, error } = await supabase
    .from("patients")
    .insert([row])
    .select()
    .single();

  if (error) throw new Error(error.message);

  return mapPatientRow(data as PatientRow);
}

export async function getPendingPatients(): Promise<PublicPatient[]> {
  const { data, error } = await supabase
    .from("patients")
    .select(
      "patient_id, full_name, status, visit_purpose, department, priority_lane, queue_number, assigned_room, estimated_wait_minutes, assigned_doctor"
    )
    .eq("status", "PENDING_RECEPTION")
    .order("registration_datetime", { ascending: true });

  if (error) return [];

  return data.map((row) => ({
    patientId: row.patient_id,
    fullName: row.full_name,
    status: row.status as PublicPatient["status"],
    visitPurpose: row.visit_purpose ?? undefined,
    department: row.department ?? undefined,
    priorityLane: row.priority_lane ?? undefined,
    queueNumber: row.queue_number ?? undefined,
    assignedRoom: row.assigned_room ?? undefined,
    estimatedWaitMinutes: row.estimated_wait_minutes ?? undefined,
    assignedDoctor: row.assigned_doctor ?? undefined,
  }));
}

